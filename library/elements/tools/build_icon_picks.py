def main():
    have = {name: {p.stem for p in d.glob("*.svg")} for name, d, _ in SETS}
    out, missing = {}, []
    for concept, (hi, cands) in C.items():
        hits = []
        for sname, d, pat in SETS:
            for c in cands:
                if c in have[sname]:
                    hits.append(f"vendor/{d.relative_to(ROOT).as_posix()}/{pat.format(c)}")
        if not hits:
            missing.append(concept); continue
        out[concept] = {"hi": hi, "file": hits[0], "alternates": hits[1:4],
                        "drawable": not hits[0].startswith("vendor/phosphor")}
    doc = {"_about": "concept -> icon file, paths relative to library/elements/. "
                      "Tabler/Lucide are stroked (draw-on with stroke-dashoffset, colour via "
                      "stroke=currentColor); Phosphor is filled. Built by tools/build_icon_picks.py.",
           "_licences": {"tabler": "MIT", "lucide": "ISC", "phosphor": "MIT"},
           "_missing": missing, "picks": out}
    (ROOT / "icon_picks.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1))
    print(len(out), "concepts picked; missing:", missing)

main()
